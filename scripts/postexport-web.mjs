#!/usr/bin/env node
// Post-processing of `expo export -p web` for GitHub Pages + offline PWA (README §4.11, Q9):
//  1. checks the PWA head tags from public/index.html and drops Expo's media-less theme-color
//  2. injects the service worker registration (only into the exported build, never in dev)
//  3. generates dist/sw.js with a content-hashed precache of every exported file
//  4. copies index.html to 404.html (deep links on GitHub Pages) and writes .nojekyll
import { createHash } from 'node:crypto';
import { copyFileSync, readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { join, relative, sep, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const dist = join(root, process.argv[2] ?? 'dist');
import { createRequire } from 'node:module';
// Base path from BASE_PATH (set in CI from actions/configure-pages), default /annuity/.
const BASE = createRequire(import.meta.url)('./base-path.cjs')();

const indexPath = join(dist, 'index.html');
let html = readFileSync(indexPath, 'utf8').replaceAll('__BASE__/', BASE);

// The manifest in public/ uses the same placeholder.
const manifestPath = join(dist, 'manifest.webmanifest');
writeFileSync(manifestPath, readFileSync(manifestPath, 'utf8').replaceAll('__BASE__/', BASE));

// Expo adds <meta name="theme-color" content="…"> from app.json web.themeColor. We use the
// per-color-scheme variants from public/index.html instead.
html = html.replace(/<meta name="theme-color" content="[^"]*"\s*\/?>\s*/g, '');

const required = [
  'viewport-fit=cover',
  'name="apple-mobile-web-app-capable"',
  'name="mobile-web-app-capable"',
  'name="apple-mobile-web-app-status-bar-style"',
  'name="apple-mobile-web-app-title"',
  'rel="apple-touch-icon"',
  'rel="manifest"',
  'name="theme-color" media="(prefers-color-scheme: light)"',
  'name="theme-color" media="(prefers-color-scheme: dark)"',
];
const missing = required.filter((s) => !html.includes(s));
if (missing.length) {
  console.error(`dist/index.html is missing PWA tags (is public/index.html in place?):\n  ${missing.join('\n  ')}`);
  process.exit(1);
}

const registration =
  `<script>if('serviceWorker' in navigator){addEventListener('load',function(){` +
  `navigator.serviceWorker.register('${BASE}sw.js',{scope:'${BASE}'}).catch(function(e){console.warn('SW registration failed',e)})})}</script>`;
if (!html.includes(`${BASE}sw.js`)) html = html.replace('</body>', `${registration}\n</body>`);
writeFileSync(indexPath, html);

// Precache list: every exported file except the SW itself and the Pages helpers.
const SKIP = new Set(['sw.js', '404.html', '.nojekyll']);
const files = [];
(function walk(dir) {
  for (const name of readdirSync(dir).sort()) {
    const p = join(dir, name);
    if (statSync(p).isDirectory()) walk(p);
    else {
      const rel = relative(dist, p).split(sep).join('/');
      if (!SKIP.has(rel) && !rel.endsWith('.map')) files.push(rel);
    }
  }
})(dist);

const hash = createHash('sha256');
for (const f of files) hash.update(f).update(readFileSync(join(dist, f)));
const version = hash.digest('hex').slice(0, 12);
// encodeURI, not encodeURIComponent: lazy route chunks such as '+not-found-….js' are requested with a literal '+'.
const urls = files.map((f) => encodeURI(BASE + f));

const sw = `// Generated by scripts/postexport-web.mjs. Do not edit.
const CACHE = 'alp-${version}';
const BASE = '${BASE}';
const INDEX = BASE + 'index.html';
const PRECACHE = ${JSON.stringify(urls)};

self.addEventListener('install', (event) => {
  event.waitUntil(caches.open(CACHE).then((c) => c.addAll(PRECACHE)).then(() => self.skipWaiting()));
});

self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches.keys()
      .then((keys) => Promise.all(keys.filter((k) => k.startsWith('alp-') && k !== CACHE).map((k) => caches.delete(k))))
      .then(() => self.clients.claim()),
  );
});

function timeout(ms) {
  return new Promise((_, reject) => setTimeout(() => reject(new Error('timeout')), ms));
}

self.addEventListener('fetch', (event) => {
  const req = event.request;
  const url = new URL(req.url);
  if (req.method !== 'GET' || url.origin !== self.location.origin || !url.pathname.startsWith(BASE)) return;

  if (req.mode === 'navigate') {
    // Network first (fresh deploys), cached app shell when offline or slow; any route works.
    event.respondWith(
      Promise.race([fetch(req), timeout(4000)])
        .then((res) => (res.ok || res.status === 404 ? res : Promise.reject(new Error(String(res.status)))))
        .catch(() => caches.match(INDEX, { cacheName: CACHE })),
    );
    return;
  }

  // Static assets are content-hashed: cache first, then network (and remember it).
  event.respondWith(
    caches.match(req, { ignoreSearch: true }).then(
      (hit) =>
        hit ||
        fetch(req).then((res) => {
          if (res.ok && res.type === 'basic') {
            const copy = res.clone();
            caches.open(CACHE).then((c) => c.put(req, copy));
          }
          return res;
        }),
    ),
  );
});
`;
writeFileSync(join(dist, 'sw.js'), sw);

copyFileSync(indexPath, join(dist, '404.html'));
writeFileSync(join(dist, '.nojekyll'), '');

const size = files.reduce((s, f) => s + statSync(join(dist, f)).size, 0);
console.log(`postexport-web: sw.js (cache alp-${version}, ${files.length} files, ${(size / 1024).toFixed(0)} KiB), 404.html, .nojekyll`);
